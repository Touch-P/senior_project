const below = ([x1, y1, x2, y2]) => [x1, y1 + 0.75, x2, y2 + 0.75];
const atEdge = ([x1, y1, x2, y2]) => { const dy = 0.985 - y2; return [x1, y1 + dy, x2, y2 + dy]; };

function story(name, meta) {
  const timeline = [];
  const objs = new Map();
  const others = (id) => [...objs.values()].filter((o) => o.id !== id);
  const api = {
    hold(sec, note) { timeline.push({ frames: Math.round(sec * FPS), ...(note ? { note } : {}), objects: [...objs.values()] }); return api; },
    /** slide in from the bottom edge (entry evidence) */
    enter(id, cls, box, conf = 0.93) {
      const o = { id, class_name: cls, conf, box };
      timeline.push({ frames: 4, note: `ADD ${cls}`, objects: [...others(id), { ...o, from: below(box) }] });
      objs.set(id, o);
      return api;
    },
    /** slide to the bottom edge, then out of the frame (exit evidence) */
    leave(id) {
      const o = objs.get(id);
      objs.delete(id);
      timeline.push({ frames: 4, note: `REMOVE ${o.class_name}`, objects: [...objs.values(), { ...o, from: o.box, box: atEdge(o.box) }] });
      timeline.push({ frames: 3, objects: [...objs.values(), { ...o, from: atEdge(o.box), box: below(o.box) }] });
      return api;
    },
    move(id, box, note) {
      const o = objs.get(id);
      timeline.push({ frames: 4, ...(note ? { note } : {}), objects: [...others(id), { ...o, from: o.box, box }] });
      objs.set(id, { ...o, box });
      return api;
    },
    /** no longer detected, without moving (hidden under something / by a hand) */
    vanish(id) { objs.delete(id); return api; },
    /** detected again in place, no motion (no entry evidence) */
    appear(id, cls, box, conf = 0.93) { objs.set(id, { id, class_name: cls, conf, box }); return api; },
    /** the model starts calling the same item another class */
    relabel(id, cls, conf) { objs.set(id, { ...objs.get(id), class_name: cls, conf }); return api; },
    build(expect) {
      return ScenarioSchema.parse({ name, description: meta.description, cart: undefined, default: false,
        source: `brief section 7.7 test ${meta.no} (generated by scripts/make-reason-scenarios.js)`,
        fps: FPS, loop: false, jitter: 0.003, seed: meta.no * 7919, infer_ms: 14, timeline, expect: { cart: meta.cart, ...expect } });
    },
  };
  return api;
}

