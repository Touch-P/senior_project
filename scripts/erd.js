// Generates Mermaid ER diagrams from the real database schema and writes them into
// docs/database.md between the ERD markers. Usage: npm run db:erd [-- --stdout]
import Database from 'better-sqlite3';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { config } from '../server/src/config.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DOC = join(ROOT, 'docs', 'database.md');
const BEGIN = '<!-- ERD:BEGIN (generated by npm run db:erd — do not edit by hand) -->';
const END = '<!-- ERD:END -->';
/** Infrastructure tables left out of the diagram. */
const SKIP = new Set(['schema_migrations']);

if (!existsSync(config.dbPath)) {
  console.error(`No database at ${config.dbPath}. Run: npm run db:init; npm run db:seed`);
  process.exit(1);
}
const db = new Database(config.dbPath, { readonly: true, fileMustExist: true });
const q = (sql, ...a) => db.prepare(sql).all(...a);

const tables = q(`SELECT name, sql FROM sqlite_master WHERE type = 'table'
                  AND name NOT LIKE 'sqlite_%' ORDER BY rowid`)
  .filter((t) => !SKIP.has(t.name) && !/^products_fts_/.test(t.name));
const isVirtual = (t) => /^CREATE VIRTUAL TABLE/i.test(t.sql);

/**
 * Columns that are unique across the whole table: single-column unique indexes that are either
 * full, or partial only to skip NULLs (e.g. barcode). Conditional ones such as "one active
 * session per cart" are not marked UK because the column itself repeats.
 */
function uniqueColumns(table) {
  const cols = new Set();
  for (const ix of q(`SELECT name, partial FROM pragma_index_list(?) WHERE "unique" = 1`, table)) {
    const parts = q('SELECT name FROM pragma_index_info(?)', ix.name);
    if (parts.length !== 1 || !parts[0].name) continue;
    const col = parts[0].name;
    if (ix.partial) {
      const sql = db.prepare("SELECT sql FROM sqlite_master WHERE type = 'index' AND name = ?").pluck().get(ix.name) ?? '';
      const where = /\bWHERE\s+(.+)$/is.exec(sql)?.[1].trim().replace(/\s+/g, ' ');
      if (where?.toLowerCase() !== `${col} is not null`.toLowerCase()) continue;
    }
    cols.add(col);
  }
  return cols;
}

const entities = [];
const relations = [];
for (const t of tables) {
  if (isVirtual(t)) {
    const cols = /fts5\(([^)]*)\)/i.exec(t.sql)?.[1].split(',').map((s) => s.trim()).filter((s) => !s.includes('=')) ?? [];
    entities.push({ name: t.name, attrs: cols.map((c) => ({ type: 'FTS5', name: c, keys: '', comment: '' })), note: 'FTS5 trigram index of products' });
    relations.push({ parent: 'products', child: t.name, line: '||--||', label: 'content_rowid' });
    continue;
  }
  const fks = q('SELECT "from", "table" AS ref FROM pragma_foreign_key_list(?)', t.name);
  const fkCols = new Map(fks.map((f) => [f.from, f.ref]));
  const uniq = uniqueColumns(t.name);
  const attrs = q('SELECT name, type, "notnull", pk FROM pragma_table_info(?)', t.name).map((c) => {
    const keys = [c.pk ? 'PK' : null, fkCols.has(c.name) ? 'FK' : null, !c.pk && uniq.has(c.name) ? 'UK' : null].filter(Boolean).join(', ');
    return { type: (c.type || 'ANY').split(/[\s(]/)[0], name: c.name, keys, comment: c.notnull || c.pk ? '' : 'nullable' };
  });
  entities.push({ name: t.name, attrs });
  for (const c of q('SELECT name, "notnull" FROM pragma_table_info(?)', t.name)) {
    if (!fkCols.has(c.name)) continue;
    // parent side: exactly one (mandatory FK) or zero-or-one (nullable FK); child side: zero or more
    relations.push({ parent: fkCols.get(c.name), child: t.name, line: c.notnull ? '||--o{' : '|o--o{', label: c.name });
  }
}

const relLines = relations.map((r) => `  ${r.parent} ${r.line} ${r.child} : "${r.label}"`);
const full = ['erDiagram', ...relLines,
  ...entities.flatMap((e) => [`  ${e.name} {`,
    ...e.attrs.map((a) => `    ${a.type} ${a.name}${a.keys ? ` ${a.keys}` : ''}${a.comment ? ` "${a.comment}"` : ''}`), '  }'])].join('\n');
const compact = ['erDiagram', ...relLines].join('\n');

const migrations = q("SELECT version FROM schema_migrations WHERE status = 'applied' ORDER BY version").map((r) => r.version);
const block = [BEGIN,
  `ที่มา: \`db/smartcart.db\` · migrations: ${migrations.map((m) => `\`${m}\``).join(', ')} · ${entities.length} ตาราง, ${relations.length} ความสัมพันธ์`,
  '',
  'สัญลักษณ์: `||--o{` = FK บังคับ (หนึ่งต่อศูนย์หรือหลาย) · `|o--o{` = FK ว่างได้ · ป้ายบนเส้น = คอลัมน์ FK ฝั่งลูก · PK / FK / UK = primary / foreign / unique key',
  '',
  '### ภาพรวมความสัมพันธ์',
  '', '```mermaid', compact, '```', '',
  '### รายละเอียดคอลัมน์',
  '', '```mermaid', full, '```',
  END].join('\n');

if (process.argv.includes('--stdout')) {
  console.log(block);
} else {
  const doc = readFileSync(DOC, 'utf8');
  const next = doc.includes(BEGIN)
    ? doc.slice(0, doc.indexOf(BEGIN)) + block + doc.slice(doc.indexOf(END) + END.length)
    : doc.trimEnd() + '\n\n## ER diagram\n\n' + block + '\n';
  writeFileSync(DOC, next);
  console.log(`ER diagram written to docs/database.md (${entities.length} tables, ${relations.length} relationships)`);
}
db.close();
