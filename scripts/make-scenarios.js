// Generate mock-mode scenarios from the prototype data (web/data.js CARTS[].boxes / outside / events).
//   npm run scenarios          writes server/test/scenarios/cart-*.json (overwrites only cart-*.json)
// Hand-written tracker scenarios (Phase 6) use other file names and are never touched.
//
// Each cart: empty basket -> items enter from the bottom edge one by one in the order of CARTS[].events
// -> hold the final basket -> items leave through the bottom edge -> loop. Events that were removed again
// (e.g. A-08 lay_big_nori ADD then REMOVE) enter and leave in between, so the abandon case is in the replay.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import vm from 'node:vm';
import { ROOT } from '../server/src/config.js';
import { expandScenario, ScenarioSchema } from '../server/src/pipeline/scenarios.js';

const OUT = resolve(ROOT, 'server', 'test', 'scenarios');
const FPS = 5;
const ENTER = 4;     // frames to slide in from the bottom edge
const SETTLE = 12;   // frames an item stays still before the next one (> TRACKER_ADD_K)
const HOLD = 40;     // frames the final basket is shown

const ctx = {};
vm.runInNewContext(readFileSync(resolve(ROOT, 'web', 'data.js'), 'utf8') + '\n;this.CARTS = CARTS;', ctx);

const below = ([x1, y1, x2, y2]) => [x1, y1 + 0.75, x2, y2 + 0.75]; // same box pushed out through the bottom edge
// same box slid down until it touches the bottom of the frame (last sighting in the ROI edge band, brief 7.2)
const atEdge = ([x1, y1, x2, y2]) => { const dy = 0.985 - y2; return [x1, y1 + dy, x2, y2 + dy]; };
/** Two segments: slide to the bottom edge, then out of the frame (a hand taking the item out of the basket). */
const leave = (others, obj, note) => [
  { frames: ENTER, note, objects: [...others, { ...obj, from: obj.box, box: atEdge(obj.box) }] },
  { frames: 3, objects: [...others, { ...obj, from: atEdge(obj.box), box: below(obj.box) }] },
];
const slug = (label) => label.toLowerCase();

function cartScenario(cart) {
  const final = cart.boxes.map(([x1, y1, x2, y2, cls, conf]) => ({ class_name: cls, conf, box: [x1, y1, x2, y2] }));
  const outside = (cart.outside ?? []).map(([x1, y1, x2, y2, cls, conf], k) => ({ id: `out${k + 1}`, class_name: cls, conf, box: [x1, y1, x2, y2] }));
  // order of arrival from the event log; classes without events keep the boxes order
  const order = [];
  const pending = final.map((b, k) => ({ ...b, id: `o${k + 1}` }));
  for (const [, type, cls] of cart.events ?? []) {
    if (type === 'ADD') {
      const k = pending.findIndex((b) => b.class_name === cls);
      if (k >= 0) order.push({ kind: 'add', obj: pending.splice(k, 1)[0] });
      else order.push({ kind: 'add', obj: { id: `x${order.length + 1}`, class_name: cls, conf: 0.93, box: [0.6, 0.55, 0.8, 0.8] }, transient: true });
    } else if (type === 'REMOVE') {
      const k = order.findIndex((o) => o.transient && o.obj.class_name === cls && !o.removed);
      if (k >= 0) { order[k].removed = true; order.push({ kind: 'remove', obj: order[k].obj }); }
    }
  }
  for (const obj of pending) order.push({ kind: 'add', obj });

  const timeline = [{ frames: 10, note: 'empty basket', objects: [...outside] }];
  let inCart = [];
  for (const step of order) {
    const others = inCart.filter((o) => o.id !== step.obj.id);
    if (step.kind === 'add') {
      timeline.push({ frames: ENTER, note: `ADD ${step.obj.class_name}`, objects: [...outside, ...others, { ...step.obj, from: below(step.obj.box) }] });
      inCart = [...others, step.obj];
    } else {
      timeline.push(...leave([...outside, ...others], step.obj, `REMOVE ${step.obj.class_name}`));
      inCart = others;
    }
    timeline.push({ frames: SETTLE, objects: [...outside, ...inCart] });
  }
  timeline.push({ frames: HOLD, note: 'final basket', objects: [...outside, ...inCart] });
  for (const obj of [...inCart].reverse()) {
    inCart = inCart.filter((o) => o.id !== obj.id);
    timeline.push(...leave([...outside, ...inCart], obj, `REMOVE ${obj.class_name} (unload)`));
    timeline.push({ frames: 2 * 8 + 6, objects: [...outside, ...inCart] }); // gone for 2W frames before the next one
  }

  const scenario = {
    name: `cart-${slug(cart.id)}`,
    description: `Replay of cart ${cart.id} from the prototype: ${final.map((b) => b.class_name).join(', ')}`
      + (outside.length ? ` (+${outside.length} box outside the ROI)` : '') + (cart.alert ? ` · ${cart.alert[1]}` : ''),
    cart: cart.id,
    default: cart.id === 'A-08',
    source: `web/data.js CARTS[${cart.id}] boxes/outside/events (generated by scripts/make-scenarios.js)`,
    fps: FPS,
    loop: true,
    jitter: 0.003,
    seed: [...cart.id].reduce((h, c) => h * 31 + c.charCodeAt(0), 7) >>> 0,
    infer_ms: cart.lat ? Math.round(cart.lat / 12) : 14,
    timeline,
    // one pass: every item goes in and comes out again (A-08: lay_big_nori is put back on the shelf in between)
    // (boxes under the model's 0.70 threshold, e.g. A-03 lay_party_ori 0.58, are never counted)
    expect: { cart: cart.id, items: {}, events: { ADD: order.filter((x) => x.kind === 'add' && x.obj.conf >= 0.7).length,
      REMOVE: order.filter((x) => x.kind === 'add' && x.obj.conf >= 0.7).length } },
  };
  return ScenarioSchema.parse(scenario);
}

mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) if (/^cart-.*\.json$/.test(f)) rmSync(join(OUT, f));
for (const cart of ctx.CARTS) {
  const sc = cartScenario(cart);
  writeFileSync(join(OUT, `${sc.name}.json`), JSON.stringify(sc, null, 2) + '\n');
  console.log(`${sc.name}.json  ${expandScenario(sc).length} frames (${(expandScenario(sc).length / FPS).toFixed(0)} s)`);
}
