// Builds web/models-data.js — the single data file behind the "โมเดล" page — from the metrics files in models/.
//
//   node scripts/build-model-data.js            (default active model: v11)
//   node scripts/build-model-data.js --default v26
//
// Layout it expects (one folder per model):
//   models/<key>/best.pt                       weights (git-ignored)
//   models/<key>/*-test-metrics.json           test-split metrics written by the training run
// Every number comes from the metrics file; a value that is not in the file is written as null and shown as "-".
// Nothing else (seed, tests, UI) hard-codes model numbers — edit/regenerate this one file instead.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MODELS_DIR = join(ROOT, 'models');
const OUT = join(ROOT, 'web', 'models-data.js');

const argDefault = process.argv.includes('--default') ? process.argv[process.argv.indexOf('--default') + 1] : 'v11';
const num = (v) => (typeof v === 'number' && Number.isFinite(v) ? v : null);
const round = (v, d) => (v == null ? null : Number(v.toFixed(d)));

/** yolo11s -> YOLO11 / s, yolov9s -> YOLOv9 / s */
function familyOf(modelName) {
  const m = /^yolo(v?\d+)([a-z]*)$/i.exec(modelName);
  return m ? { family: `YOLO${m[1]}`, size: m[2] || null } : { family: modelName, size: null };
}

const models = [];
for (const key of readdirSync(MODELS_DIR, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  const dir = join(MODELS_DIR, key);
  const metricsFile = readdirSync(dir).find((f) => f.endsWith('-test-metrics.json'));
  if (!metricsFile) continue;
  const m = JSON.parse(readFileSync(join(dir, metricsFile), 'utf8'));
  const weights = ['best.pt', 'best.onnx', 'best.engine'].find((f) => existsSync(join(dir, f)));
  const { family, size } = familyOf(m.model_name);
  models.push({
    // the seed number is deliberately not part of the name: it only exists to show the result is not luck
    name: `${m.model_name}-${m.run_date}`,
    key,
    family,
    size,
    format: (weights ?? 'best.pt').split('.').pop(),
    weights_path: `${key}/${weights ?? 'best.pt'}`,
    imgsz: m.protocol?.imgsz ?? null,
    map50_95: round(num(m.map50_95), 4),
    map50: round(num(m.map50), 4),
    precision: round(num(m.precision), 4),
    recall: round(num(m.recall), 4),
    params: num(m.params),
    gflops: round(num(m.gflops), 1),
    latency_p95_ms: null, // not in the metrics files
    per_class: (m.per_class ?? []).map((c) => ({
      name: c.name, ap50_95: round(num(c.ap50_95), 4), ap50: round(num(c.ap50), 4),
      precision: round(num(c.precision), 4), recall: round(num(c.recall), 4), instances: num(c.instances),
    })),
  });
}
if (!models.length) throw new Error(`no *-test-metrics.json found under ${MODELS_DIR}`);
models.sort((a, b) => (b.map50_95 ?? 0) - (a.map50_95 ?? 0));
const def = models.find((x) => x.key === argDefault);
if (!def) throw new Error(`--default ${argDefault}: no such model folder`);

const data = { default_active: def.name, split: 'test', models };
const banner = `// Single data file for the model page (web) and the model_versions seed (server/src/db/seed.js).
// Generated by scripts/build-model-data.js from models/*/*-test-metrics.json — do not edit numbers by hand.
// null = not in the metrics file (the page shows "-").
`;
writeFileSync(OUT, `${banner}globalThis.MODEL_DATA = ${JSON.stringify(data, null, 1)};\n`);
console.log(`wrote ${OUT}: ${models.length} models, default active = ${def.name}`);
